-- Per-line cost: €/m² (or per unit of the line's measure), without VAT. Admin-only in the API.
ALTER TABLE order_items ADD COLUMN IF NOT EXISTS cost_rate NUMERIC(10,2);
ALTER TABLE order_items ADD COLUMN IF NOT EXISTS glass_spec JSONB;

-- Imported lines already carry their spreadsheet cost: keep it as a rate so that editing a size or the
-- quantity re-scales the cost instead of re-deriving it with default waste.
UPDATE order_items SET cost_rate = ROUND(line_cost / billed_qty, 2)
 WHERE cost_rate IS NULL AND line_cost IS NOT NULL AND billed_qty > 0;

