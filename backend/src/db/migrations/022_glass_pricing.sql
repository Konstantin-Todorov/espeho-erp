-- 022: glass price list and the spreadsheet cost formula.
-- Base glasses come from the price sheets of „ПОРЪЧКИ 2026-ЕВРО.xlsx“: „Единичен“ (supply price + labour for a single pane)
-- and „Двойни/Тройни пакети“ (glass price inside an insulated unit). Default waste (фира) is the median used in real orders.
-- Item cost per m² (without VAT), exactly as the spreadsheet column СЕБЕСТОЙНОСТ:
--   single: price·(1+waste) + labour
--   double: Σ glass·(1+waste) + igu2_consumables + igu2_labor
--   triple: Σ glass·(1+waste) + igu3_consumables + igu3_labor

CREATE TABLE IF NOT EXISTS glass_types (
  id            SERIAL PRIMARY KEY,
  name          VARCHAR(120) NOT NULL UNIQUE,
  category      VARCHAR(60),
  supply_price  NUMERIC(10,2),          -- €/m² without VAT, single pane (sheet „Единичен“ B)
  labor_price   NUMERIC(10,2),          -- €/m² labour for a single pane (sheet „Единичен“ C)
  igu_price     NUMERIC(10,2),          -- €/m² of this glass inside an insulated unit (sheets „Двойни/Тройни пакети“)
  waste_pct     NUMERIC(5,2) NOT NULL DEFAULT 7.5,
  uses          INTEGER NOT NULL DEFAULT 0,  -- how often it appeared in the spreadsheet (for sorting)
  active        BOOLEAN NOT NULL DEFAULT true,
  sort_order    INTEGER NOT NULL DEFAULT 0,
  updated_at    TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

